import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { $ } from 'bun';
import { build, type Plugin } from 'vite';

const here = import.meta.dir;
const app = join(here, '../..');
const output = join(app, '../THIRD-PARTY-LICENSES');

// CSS pulled in by `@import` and the helpers Vite writes into the bundle aren't modules of it.
const notModules = ['tailwindcss', 'vite'];

function packageOf(path: string): string | null {
  const found = [...path.matchAll(/node_modules\/((?:@[^/]+\/)?[^/]+)/g)].at(-1);
  return found?.[1] ?? null;
}

async function bundledPackages(): Promise<string[]> {
  const packages = new Set(notModules);
  const collect: Plugin = {
    name: 'collect-packages',
    generateBundle(_, bundle) {
      const paths = Object.values(bundle).flatMap((file) =>
        file.type === 'chunk' ? Object.keys(file.modules) : file.originalFileNames,
      );
      for (const path of paths) {
        const name = packageOf(path);
        if (name) packages.add(name);
      }
    },
  };
  await build({
    root: app,
    logLevel: 'warn',
    plugins: [collect],
    build: { write: false },
  });
  return [...packages].sort();
}

function frontendSection(name: string): string {
  const folder = dirname(Bun.resolveSync(`${name}/package.json`, app));
  const { version, license } = JSON.parse(readFileSync(join(folder, 'package.json'), 'utf8'));
  const files = readdirSync(folder).filter((file) => /^(licen[cs]e|copying|notice)/i.test(file));
  if (files.length === 0) throw new Error(`${name} has no licence file`);
  const texts = files.map((file) => readFileSync(join(folder, file), 'utf8').trim());
  return `${'-'.repeat(80)}\n${name} ${version} (${license})\n\n${texts.join('\n\n')}\n`;
}

type RustLicense = {
  name: string;
  text: string;
  used_by: { crate: { name: string; version: string } }[];
};

const report =
  await $`cargo about generate --workspace --locked --fail --format json -m ../Cargo.toml -c scripts/licenses/about.toml`
    .cwd(app)
    .quiet()
    .json();
const rust = (report.licenses as RustLicense[])
  .map(({ name, text, used_by }) => {
    const crates = used_by.map(({ crate }) => `- ${crate.name} ${crate.version}`).join('\n');
    return `${'-'.repeat(80)}\n${name}\n\nUsed by:\n${crates}\n\n${text.trim()}\n`;
  })
  .join('\n');
const frontend = (await bundledPackages()).map(frontendSection).join('\n');

writeFileSync(
  output,
  `Third-party software in Ela, generated by \`bun run licenses\`. Edits here are overwritten.

This software is based in part on the work of the Independent JPEG Group.

${'='.repeat(80)}
Rust crates
${'='.repeat(80)}

${rust}

${'='.repeat(80)}
Frontend packages and fonts
${'='.repeat(80)}

${frontend}`,
);
